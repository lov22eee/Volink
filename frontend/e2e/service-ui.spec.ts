const curated = ['옥정중앙공원', '독바위공원', '회암사지 역사공원']

// Without a Kakao REST key (local development) the place dialog lists the admin-entered places.
async function pickPlace(page: Page, name: string, meetingPoint = '') {
  await page.getByRole('button', { name: /장소를 골라 주세요|공원/ }).first().click()
  const dialog = page.getByRole('dialog', { name: '장소 찾기' })
  await dialog.getByRole('button', { name: new RegExp(name) }).click()
  if (meetingPoint) await dialog.getByRole('textbox', { name: /만나는 곳/ }).fill(meetingPoint)
  await dialog.getByRole('button', { name: '이 장소로 정하기' }).click()
  await expect(dialog).toHaveCount(0)
}

// Date through the calendar: next month until the day shows, then the day.
async function pickDate(page: Page, date: string) {
  await page.getByRole('button', { name: /^활동 날짜/ }).click()
  const calendar = page.getByRole('dialog', { name: '날짜 고르기' })
  for (let i = 0; i < 3 && !(await calendar.locator(`[data-date="${date}"]`).count()); i++) await calendar.getByRole('button', { name: '다음 달' }).click()
  await calendar.locator(`[data-date="${date}"]`).click()
}

// Start time through the wheel: "오전|오후", hour, minute.
async function pickTime(page: Page, time: string) {
  const [h, m] = time.split(':').map(Number)
  await page.getByRole('button', { name: /^시작 시간/ }).click()
  const wheel = page.getByRole('dialog', { name: '시작 시간 고르기' })
  await wheel.getByRole('listbox', { name: '오전 오후' }).getByRole('option', { name: h < 12 ? '오전' : '오후' }).click()
  await wheel.getByRole('listbox', { name: '시', exact: true }).getByRole('option', { name: String(h % 12 === 0 ? 12 : h % 12), exact: true }).click()
  await wheel.getByRole('listbox', { name: '분' }).getByRole('option', { name: String(m).padStart(2, '0'), exact: true }).click()
  await wheel.getByRole('button', { name: '완료' }).click()
}

async function chooseType(page: Page, text: string) {
  await page.getByRole('button', { name: /^활동 유형/ }).click()
  await page.getByRole('listbox', { name: '활동 유형' }).getByRole('option', { name: new RegExp(text) }).click()
}

async function fillActivity(page: Page, title: string, description: string, time = '10:00', place = 1) {
  await page.goto('/#/create')
  await page.getByLabel(/활동 이름/).fill(title)
  await pickPlace(page, curated[place - 1])
  await pickDate(page, seoulDate(7))
  if (time !== '10:00') await pickTime(page, time)
  await page.getByLabel(/활동 소개/).fill(description)
  await page.getByRole('checkbox', { name: /공공장소의 저위험 활동/ }).check()
}

// Lists show 9 per page, so a new post is found through the search box (it filters as you type).
async function searchFor(page: Page, words: string) {
  const box = page.getByRole('textbox', { name: '활동 검색' })
  if (!(await box.isVisible())) await page.getByRole('button', { name: '검색', exact: true }).click()
  await box.fill(words)
}

// Korean calendar date N days from now, used so date rules stay valid whenever the suite runs.
function seoulDate(days: number) {
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Seoul' }).format(new Date(Date.now() + days * 86_400_000))
}

