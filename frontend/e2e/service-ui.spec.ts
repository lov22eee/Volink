// The demo admin account exists only in the local dev environment; its password lives in the ignored ../.env.
function demoPassword() {
  const line = readFileSync(new URL('../../.env', import.meta.url), 'utf8').split('\n').find(row => row.startsWith('DEMO_ACCOUNT_PASSWORD='))
  if (!line) throw new Error('Run ./scripts/setup-env.sh so DEMO_ACCOUNT_PASSWORD exists')
  return line.slice('DEMO_ACCOUNT_PASSWORD='.length).trim()
}

function uniqueEmail(prefix: string) {
  return `${prefix}-${Date.now()}-${Math.floor(Math.random() * 1e6)}@example.com`
}

async function signup(page: Page, options: { institution?: boolean } = {}) {
  const email = uniqueEmail(options.institution ? 'org' : 'member')
  await page.goto('/#/signup')
  if (options.institution) await page.getByRole('radio', { name: /기관회원/ }).check()
  await page.getByRole('textbox', { name: '이름', exact: true }).fill(options.institution ? '기관 담당' : '테스트 회원')
  await page.getByLabel(/생년월일/).fill('2000-01-01')
  await page.getByRole('checkbox', { name: '환경 정화' }).check()
  if (options.institution) {
    await page.getByRole('textbox', { name: '기관명', exact: true }).fill('테스트 기관')
    await page.getByLabel('기관 연락처').fill('000-0000-0000')
  }
  await page.getByRole('textbox', { name: '이메일', exact: true }).fill(email)
  await page.getByRole('textbox', { name: /^비밀번호 영문/ }).fill(password)
  await page.getByRole('textbox', { name: '비밀번호 확인', exact: true }).fill(password)
  await page.getByRole('checkbox', { name: /공식 봉사실적/ }).check()
  await page.getByRole('button', { name: '가입하기' }).click()
  await expect(page).toHaveURL(/#\/mine$/)
  return email
}

