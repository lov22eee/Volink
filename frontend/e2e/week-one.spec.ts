  await expect(page.getByLabel('기관명', { exact: true })).toHaveCount(0)
  await page.getByRole('radio', { name: /기관회원/ }).check()
  await page.getByLabel('이름', { exact: true }).fill('예시 사용자')
  await page.getByLabel('기관명', { exact: true }).fill('예시 기관')
